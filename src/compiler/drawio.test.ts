import { describe, expect, it } from "vitest";
import { extractMxfile, isDrawioSvg, mxfilePageName, normalizeDrawioSvg } from "./drawio.js";

// Minimal mock of draw.io's File > Export as > SVG. Has the real structure: prolog / DOCTYPE, the
// mxfile in the content attribute, a foreignObject label, and the trailing drawio.com fallback
// link.
const drawioSvg = (opts: { page?: string; fill?: string; withContent?: boolean } = {}): string => {
    const { page = "auth route", fill = "#dae8fc", withContent = true } = opts;
    // The content attribute (mxfile) is what gets dropped from the artifact. Give it real content
    // so a failure to drop it is detectable.
    const mxfile = `<mxfile host="app.diagrams.net"><diagram name="${page}" id="a"><mxGraphModel><root><mxCell style="fillColor=#ff00ff;strokeColor=#123456"/></root></mxGraphModel></diagram></mxfile>`;
    const content = withContent
        ? ` content="${mxfile.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")}"`
        : "";
    return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">',
        `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="background: transparent; background-color: transparent; color-scheme: light dark;" width="241px" height="121px" viewBox="-0.5 -0.5 241 121"${content}>`,
        "<defs/><g>",
        // draw.io emits both presentation attributes (fallback for old renderers) and
        // light-dark() CSS.
        `<style>.shape{fill: light-dark(rgb(218,232,252), rgb(29,41,59)); stroke: light-dark(rgb(0,0,0), rgb(255,255,255));}</style>`,
        `<rect class="shape" x="0" y="0" width="240" height="120" fill="${fill}" stroke="#6c8ebf"/>`,
        '<g><switch><foreignObject width="100%" height="100%"><div xmlns="http://www.w3.org/1999/xhtml" style="font-size: 12px; color: rgb(0, 0, 0);">Label</div></foreignObject>',
        '<text x="120" y="64" fill="rgb(0, 0, 0)" text-anchor="middle">Label</text></switch></g>',
        "</g>",
        '<switch><g requiredFeatures="http://www.w3.org/TR/SVG11/feature#Extensibility"/><a transform="translate(0,-5)" xlink:href="https://www.drawio.com/doc/faq/svg-export-text-problems" target="_blank"><text>Text is not SVG - cannot display</text></a></switch>',
        "</svg>",
    ].join("\n");
};

describe("normalizeDrawioSvg", () => {
    it("drops the prolog / DOCTYPE / content attribute / external link, leaving a single root <svg>", () => {
        const { markup } = normalizeDrawioSvg("auth", drawioSvg());
        expect(markup.startsWith("<svg")).toBe(true);
        expect(markup.endsWith("</svg>")).toBe(true);
        expect(markup).not.toContain("<?xml");
        expect(markup).not.toContain("<!DOCTYPE");
        // No editing data or external domains left in the shipped artifact.
        expect(markup).not.toContain("mxfile");
        expect(markup).not.toContain("drawio.com");
        expect(markup).not.toContain("Text is not SVG");
    });

    it("strips down to the root <svg> even in the Save format (.drawio.svg) with a draw.io comment in the prolog", () => {
        const saved = drawioSvg().replace(
            "\n<!DOCTYPE",
            "\n<!-- Do not edit this file with editors other than draw.io -->\n<!DOCTYPE",
        );
        const { markup } = normalizeDrawioSvg("auth", saved);
        expect(markup.startsWith("<svg")).toBe(true);
        expect(markup).not.toContain("Do not edit this file");
        expect(markup).not.toContain("<!DOCTYPE");
    });

    it("keeps draw.io colors as-is (does not map them to the docs palette)", () => {
        // draw.io carries both light/dark values itself via light-dark(), so leaving colors
        // untouched is correct.
        const { markup } = normalizeDrawioSvg("auth", drawioSvg());
        expect(markup).toContain("light-dark(rgb(218,232,252), rgb(29,41,59))");
        expect(markup).toContain('fill="#dae8fc"');
        expect(markup).toContain('stroke="#6c8ebf"');
        // No shape color is mapped to a docs token (the only exception is the injected
        // --ge-dark-color).
        expect(markup).not.toMatch(/(?:fill|stroke)="var\(--doc-/);
        expect(markup).not.toMatch(/(?:fill|stroke):\s*var\(--doc-/);
    });

    it("passes off-palette colors through unchanged (does not restrict diagram colors)", () => {
        const { markup } = normalizeDrawioSvg("auth", drawioSvg({ fill: "#ff8800" }));
        expect(markup).toContain('fill="#ff8800"');
    });

    it("removes the root color-scheme and points only the dark-mode surface color at docs", () => {
        // If the inline color-scheme stayed, it would beat figures.ts's theme injection and the
        // figure alone would follow the OS light/dark setting (not the docs theme toggle).
        const { markup } = normalizeDrawioSvg("auth", drawioSvg());
        const head = markup.slice(0, markup.indexOf(">"));
        expect(head).not.toMatch(/color-scheme\s*:/);
        expect(head).toContain("--ge-dark-color: var(--doc-panel, #161b22)");
        // Other declarations are kept.
        expect(head).toContain("background: transparent");
    });

    it("title is always Fig.<name>, desc is the draw.io page name", () => {
        const { markup, desc } = normalizeDrawioSvg("auth-flow", drawioSvg());
        expect(desc).toBe("auth route");
        expect(markup).toContain("<title>Fig.auth-flow</title>");
        expect(markup).toContain("<desc>auth route</desc>");
    });

    it("omits desc without an error when the page name is still the default", () => {
        // <desc> is optional for figures/*.svg too. One freshly started figure shouldn't fail
        // validation of the whole docs.
        const { markup, desc } = normalizeDrawioSvg("auth", drawioSvg({ page: "Page-1" }));
        expect(desc).toBeUndefined();
        expect(markup).not.toContain("<desc>");
        expect(markup).toContain("<title>Fig.auth</title>");
    });

    it("accepts an SVG exported without the diagram copy (only desc is unavailable)", () => {
        // The SVG can be imported even when the export doesn't include the mxfile.
        const { markup, desc } = normalizeDrawioSvg("auth", drawioSvg({ withContent: false }));
        expect(desc).toBeUndefined();
        expect(markup).toContain("<title>Fig.auth</title>");
        expect(markup).not.toContain("drawio.com");
    });
});

describe("isDrawioSvg", () => {
    it("detects draw.io exports (both with and without the copy)", () => {
        expect(isDrawioSvg(drawioSvg())).toBe(true);
        expect(isDrawioSvg(drawioSvg({ withContent: false }))).toBe(true);
        // Also detected when the only trace is an inline color-scheme on the root.
        expect(
            isDrawioSvg(
                '<svg xmlns="http://www.w3.org/2000/svg" style="color-scheme: light dark;"><g/></svg>',
            ),
        ).toBe(true);
    });

    it("leaves hand-written figures alone", () => {
        expect(
            isDrawioSvg(
                '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1 1"><title>Fig.hand</title><rect fill="var(--doc-panel, #fff)"/></svg>',
            ),
        ).toBe(false);
    });
});

describe("extractMxfile / mxfilePageName", () => {
    it("restores the mxfile from the content attribute and reads the page name", () => {
        const mxfile = extractMxfile(drawioSvg({ page: "Route & boundary" }));
        expect(mxfile).toContain("<mxfile");
        expect(mxfilePageName(mxfile ?? "")).toBe("Route & boundary");
    });

    it("returns undefined without a content attribute", () => {
        expect(extractMxfile(drawioSvg({ withContent: false }))).toBeUndefined();
    });
});
