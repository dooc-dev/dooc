import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const { version } = JSON.parse(readFileSync("package.json", "utf8"));
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error("Expected a stable package version");
const platforms = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"];
const sums = platforms.map((platform) => {
    const file = `dooc-${platform}.tar.gz`;
    const hash = createHash("sha256")
        .update(readFileSync(`build/releases/${file}`))
        .digest("hex");
    return { platform, file, hash };
});
writeFileSync(
    "build/releases/SHA256SUMS",
    sums.map(({ hash, file }) => `${hash}  ${file}\n`).join(""),
);
const stanza = (os, arch) => {
    const { file, hash } = sums.find(({ platform }) => platform === `${os}-${arch}`);
    return `    on_${arch === "arm64" ? "arm" : "intel"} do
      url "https://github.com/sasaki-s-sci/dooc/releases/download/v${version}/${file}"
      sha256 "${hash}"
    end`;
};
mkdirSync("Formula", { recursive: true });
writeFileSync(
    "Formula/dooc.rb",
    `# Generated by scripts/prepare-release.mjs.
class Dooc < Formula
  desc "Compile, preview, and edit documentation"
  homepage "https://github.com/sasaki-s-sci/dooc"
  version "${version}"

  on_macos do
${stanza("darwin", "arm64")}
${stanza("darwin", "x64")}
  end

  on_linux do
${stanza("linux", "arm64")}
${stanza("linux", "x64")}
  end

  def install
    bin.install "dooc"
  end

  test do
    assert_match "usage: dooc", shell_output("#{bin}/dooc --help")
  end
end
`,
);
